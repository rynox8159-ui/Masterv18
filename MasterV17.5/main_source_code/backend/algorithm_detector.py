"""Heavy market-algorithm detection layer (V16.3).

Detects how the price engine behaves on closed candles so 1m/5m signals only fire
when a measurable, repeatable edge exists. Works for real Deriv forex pairs and for
broker/OTC (binary) feeds whose candles are generated by a pricing algorithm.

Detectors (each returns direction, probability and a sample-size aware edge):
  D1 hurst_regime      - rescaled-range Hurst exponent: trending (>0.55) / mean-reverting (<0.45)
  D2 autocorrelation   - lag-1/2 return autocorrelation (momentum vs. reversal engine)
  D3 color_ngram       - next-candle colour frequency after the last k colours (k=2..4)
  D4 streak_exhaustion - historical continuation probability after an N-candle run
  D5 wick_rejection    - rejection wicks at range extremes
  D6 volatility_regime - ATR percentile (dead / normal / explosive)
  D7 range_position    - z-score of close inside the rolling range (stretch -> snap back)
  D8 cycle_phase       - dominant cycle via FFT on detrended closes
The fused verdict exposes a regime label, an algorithmic edge and vetoes used by the
signal engine and the auto-trade safety gate.
"""
import math
import os
from typing import Any, Dict, List, Sequence

import numpy as np

MIN_CANDLES = 60
STRICT = os.environ.get('ALGO_LAYER_STRICT', 'true').strip().lower() == 'true'
MIN_EDGE = float(os.environ.get('ALGO_LAYER_MIN_EDGE', '0.04'))
MIN_OOS_HIT_RATE = float(os.environ.get('ALGO_MIN_OOS_HIT_RATE', '0.56'))
MIN_OOS_SAMPLES = int(os.environ.get('ALGO_MIN_OOS_SAMPLES', '40'))
MIN_DETECTOR_HIT_RATE = float(os.environ.get('ALGO_MIN_DETECTOR_HIT_RATE', '0.54'))
PROFILE_TTL_SECONDS = int(os.environ.get('ALGO_PROFILE_TTL_SECONDS', '1200'))
PROFILES: Dict[Any, Dict[str, Any]] = {}


def _closes(candles):
    return np.asarray([float(c['close']) for c in candles], dtype=float)


def _colors(candles):
    return [1 if float(c['close']) > float(c['open']) else -1 if float(c['close']) < float(c['open']) else 0 for c in candles]


def _vote(name, direction, probability, samples, detail):
    probability = float(min(0.95, max(0.05, probability)))
    edge = abs(probability - 0.5) * min(1.0, math.sqrt(max(samples, 0)) / 10.0)
    return {'name': name, 'direction': direction if edge > 0.005 else 'NEUTRAL', 'probability': round(probability, 4),
            'edge': round(edge, 4), 'samples': int(samples), 'detail': detail}


def hurst_exponent(series: np.ndarray) -> float:
    returns = np.diff(np.log(np.maximum(series, 1e-12)))
    if len(returns) < 32:
        return 0.5
    sizes = [n for n in (8, 16, 32, 64, 128) if n <= len(returns) // 2]
    rs = []
    for size in sizes:
        chunks = [returns[i:i + size] for i in range(0, len(returns) - size + 1, size)]
        values = []
        for chunk in chunks:
            dev = np.cumsum(chunk - chunk.mean())
            spread, std = dev.max() - dev.min(), chunk.std()
            if std > 0:
                values.append(spread / std)
        if values:
            rs.append((math.log(size), math.log(np.mean(values))))
    if len(rs) < 2:
        return 0.5
    x, y = zip(*rs)
    return float(np.clip(np.polyfit(x, y, 1)[0], 0.0, 1.0))


def _last_direction(candles):
    return 1 if float(candles[-1]['close']) >= float(candles[-1]['open']) else -1


def detect_hurst(candles):
    closes = _closes(candles)
    h = hurst_exponent(closes)
    last = _last_direction(candles)
    if h > 0.55:
        direction, p = ('CALL' if last > 0 else 'PUT'), 0.5 + (h - 0.5) * 0.6
    elif h < 0.45:
        direction, p = ('PUT' if last > 0 else 'CALL'), 0.5 + (0.5 - h) * 0.6
    else:
        direction, p = 'NEUTRAL', 0.5
    return _vote('hurst_regime', direction, p, len(closes) // 3, f'H={h:.3f}'), h


def detect_autocorrelation(candles):
    returns = np.diff(_closes(candles))
    if len(returns) < 20 or returns.std() == 0:
        return _vote('autocorrelation', 'NEUTRAL', 0.5, 0, 'flat'), 0.0
    ac1 = float(np.corrcoef(returns[:-1], returns[1:])[0, 1])
    ac1 = 0.0 if math.isnan(ac1) else ac1
    last = 1 if returns[-1] > 0 else -1
    sign = last if ac1 > 0 else -last
    p = 0.5 + min(0.3, abs(ac1) * 0.5)
    return _vote('autocorrelation', 'CALL' if sign > 0 else 'PUT', p, len(returns), f'ac1={ac1:+.3f}'), ac1


def detect_color_ngram(candles):
    colors = [c for c in _colors(candles) if c != 0]
    best = _vote('color_ngram', 'NEUTRAL', 0.5, 0, 'insufficient colours')
    for k in (2, 3, 4):
        if len(colors) < k + 30:
            continue
        key = tuple(colors[-k:])
        nxt = [colors[i + k] for i in range(len(colors) - k) if tuple(colors[i:i + k]) == key]
        if len(nxt) < 6:
            continue
        ups = sum(1 for c in nxt if c > 0)
        p_up = (ups + 1) / (len(nxt) + 2)
        vote = _vote('color_ngram', 'CALL' if p_up >= 0.5 else 'PUT', max(p_up, 1 - p_up), len(nxt), f'k={k} pattern {key} -> up {ups}/{len(nxt)}')
        if vote['edge'] > best['edge']:
            best = vote
    return best


def detect_streak(candles):
    colors = [c for c in _colors(candles) if c != 0]
    if len(colors) < 40:
        return _vote('streak_exhaustion', 'NEUTRAL', 0.5, 0, 'insufficient')
    run, last = 1, colors[-1]
    for c in reversed(colors[:-1]):
        if c != last:
            break
        run += 1
    cont = total = 0
    i = 0
    while i < len(colors) - 1:
        j = i
        while j + 1 < len(colors) and colors[j + 1] == colors[i]:
            j += 1
        length = j - i + 1
        if length >= run and j + 1 < len(colors):
            total += 1
            cont += 1 if length > run else 0
        i = j + 1
    if total < 5:
        return _vote('streak_exhaustion', 'NEUTRAL', 0.5, total, f'run {run} rarely seen')
    p_cont = (cont + 1) / (total + 2)
    direction = ('CALL' if last > 0 else 'PUT') if p_cont >= 0.5 else ('PUT' if last > 0 else 'CALL')
    return _vote('streak_exhaustion', direction, max(p_cont, 1 - p_cont), total, f'run {run} continues {cont}/{total}')


def detect_wick_rejection(candles):
    recent = candles[-20:]
    highs = max(float(c['high']) for c in recent)
    lows = min(float(c['low']) for c in recent)
    c = candles[-1]
    o, h, l, cl = (float(c[k]) for k in ('open', 'high', 'low', 'close'))
    body = abs(cl - o) or 1e-12
    upper, lower = h - max(o, cl), min(o, cl) - l
    span = (highs - lows) or 1e-12
    if upper > 2 * body and (highs - h) / span < 0.1:
        return _vote('wick_rejection', 'PUT', 0.5 + min(0.2, upper / span), 12, 'upper rejection at range high')
    if lower > 2 * body and (l - lows) / span < 0.1:
        return _vote('wick_rejection', 'CALL', 0.5 + min(0.2, lower / span), 12, 'lower rejection at range low')
    return _vote('wick_rejection', 'NEUTRAL', 0.5, 0, 'no rejection')


def atr_percentile(candles, period=14):
    trs = [max(float(c['high']) - float(c['low']), abs(float(c['high']) - float(p['close'])), abs(float(c['low']) - float(p['close'])))
           for p, c in zip(candles[:-1], candles[1:])]
    if len(trs) < period * 3:
        return 50.0
    atr = np.convolve(trs, np.ones(period) / period, mode='valid')
    return float((atr < atr[-1]).mean() * 100.0)


def detect_range_position(candles, window=30):
    closes = _closes(candles[-window:])
    std = closes.std()
    if std == 0:
        return _vote('range_position', 'NEUTRAL', 0.5, 0, 'flat'), 0.0
    z = float((closes[-1] - closes.mean()) / std)
    if abs(z) < 1.6:
        return _vote('range_position', 'NEUTRAL', 0.5, 0, f'z={z:+.2f}'), z
    return _vote('range_position', 'PUT' if z > 0 else 'CALL', 0.5 + min(0.2, (abs(z) - 1.6) * 0.15 + 0.04), window, f'stretched z={z:+.2f}'), z


def detect_cycle(candles):
    closes = _closes(candles[-128:])
    if len(closes) < 64:
        return _vote('cycle_phase', 'NEUTRAL', 0.5, 0, 'insufficient')
    detrended = closes - np.polyval(np.polyfit(np.arange(len(closes)), closes, 1), np.arange(len(closes)))
    spectrum = np.abs(np.fft.rfft(detrended))[1:]
    if not spectrum.size or spectrum.sum() == 0:
        return _vote('cycle_phase', 'NEUTRAL', 0.5, 0, 'no cycle')
    k = int(np.argmax(spectrum)) + 1
    power = float(spectrum[k - 1] / spectrum.sum())
    period = len(closes) / k
    phase = np.angle(np.fft.rfft(detrended)[k])
    t = len(closes)
    slope_next = -math.sin(2 * math.pi * k * t / len(closes) + phase)
    if power < 0.18 or period < 4:
        return _vote('cycle_phase', 'NEUTRAL', 0.5, 0, f'weak cycle p={period:.1f}')
    return _vote('cycle_phase', 'CALL' if slope_next > 0 else 'PUT', 0.5 + min(0.15, power * 0.3), int(len(closes) / period) * 3, f'period {period:.1f} power {power:.2f}')


def detect(candles: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    candles = [c for c in candles if all(k in c for k in ('open', 'high', 'low', 'close'))]
    if len(candles) < MIN_CANDLES:
        return {'ready': False, 'direction': 'NO_SIGNAL', 'edge': 0.0, 'regime': 'INSUFFICIENT_DATA', 'detectors': [], 'vetoes': []}
    hurst_vote, h = detect_hurst(candles)
    ac_vote, ac1 = detect_autocorrelation(candles)
    range_vote, z = detect_range_position(candles)
    detectors: List[Dict[str, Any]] = [hurst_vote, ac_vote, detect_color_ngram(candles), detect_streak(candles),
                                       detect_wick_rejection(candles), range_vote, detect_cycle(candles)]
    atr_pct = atr_percentile(candles)
    flat = sum(1 for c in candles[-20:] if float(c['close']) == float(c['open'])) / 20.0
    score = sum((1 if d['direction'] == 'CALL' else -1 if d['direction'] == 'PUT' else 0) * d['edge'] for d in detectors)
    total_edge = sum(d['edge'] for d in detectors) or 1e-9
    direction = 'CALL' if score > 0 else 'PUT' if score < 0 else 'NO_SIGNAL'
    edge = abs(score) / max(1.0, len(detectors) / 3)
    agreement = abs(score) / total_edge
    if h > 0.55 and ac1 > 0.05:
        regime = 'TRENDING_MOMENTUM_ENGINE'
    elif h < 0.45 or ac1 < -0.08:
        regime = 'MEAN_REVERTING_ENGINE'
    elif flat > 0.35:
        regime = 'FLAT_DEAD_MARKET'
    else:
        regime = 'RANDOM_WALK'
    vetoes = []
    if atr_pct < 5:
        vetoes.append('ALGO_DEAD_VOLATILITY')
    if atr_pct > 97:
        vetoes.append('ALGO_EXPLOSIVE_VOLATILITY')
    if regime == 'FLAT_DEAD_MARKET':
        vetoes.append('ALGO_FLAT_MARKET')
    if regime == 'RANDOM_WALK' and edge < MIN_EDGE:
        vetoes.append('ALGO_RANDOM_WALK_NO_EDGE')
    return {
        'ready': True, 'direction': direction, 'edge': round(edge, 4), 'agreement': round(agreement, 3),
        'probability': round(0.5 + min(0.3, edge), 4), 'regime': regime, 'hurst': round(h, 3), 'autocorr': round(ac1, 3),
        'rangeZ': round(z, 2), 'atrPercentile': round(atr_pct, 1), 'flatRatio': round(flat, 2),
        'detectors': detectors, 'vetoes': vetoes,
    }


def wilson_lower_bound(hits, total, z=1.96):
    if not total:
        return 0.0
    p = hits / total
    centre = p + z * z / (2 * total)
    margin = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total))
    return (centre - margin) / (1 + z * z / total)


def _next_color(candle):
    o, c = float(candle['open']), float(candle['close'])
    return 1 if c > o else -1 if c < o else 0


def _fused(votes, validated):
    score = sum((1 if d == 'CALL' else -1) * w for name, (d, w) in votes.items() if name in validated and d in {'CALL', 'PUT'})
    return 'CALL' if score > 0 else 'PUT' if score < 0 else None


def build_profile(candles: Sequence[Dict[str, Any]], window: int = 200, max_points: int = 420, train_fraction: float = 0.65) -> Dict[str, Any]:
    """Walk-forward test of every detector on THIS market's own history (no look-ahead).

    First 65% of points choose the detectors that really predicted the next candle;
    the last 35% measure the fused out-of-sample hit-rate that gates live signals.
    """
    candles = [c for c in candles if all(k in c for k in ('open', 'high', 'low', 'close'))]
    start = max(MIN_CANDLES, len(candles) - 1 - max_points)
    rows = []
    for i in range(start, len(candles) - 1):
        actual = _next_color(candles[i + 1])
        if actual == 0:
            continue
        report = detect(candles[max(0, i + 1 - window):i + 1])
        if not report['ready']:
            continue
        votes = {d['name']: (d['direction'], max(d['edge'], 1e-3)) for d in report['detectors']}
        rows.append((votes, actual, report['vetoes']))
    split = int(len(rows) * train_fraction)
    train, test = rows[:split], rows[split:]
    stats = {}
    for votes, actual, _ in train:
        for name, (direction, _w) in votes.items():
            if direction in {'CALL', 'PUT'}:
                hit, total = stats.get(name, (0, 0))
                stats[name] = (hit + ((direction == 'CALL') == (actual > 0)), total + 1)
    detectors = {name: {'hitRate': round(h / t, 4), 'samples': t} for name, (h, t) in stats.items() if t}
    validated = {name for name, v in detectors.items() if v['samples'] >= 25 and v['hitRate'] >= MIN_DETECTOR_HIT_RATE}
    hits = total = 0
    for votes, actual, vetoes in test:
        if vetoes:
            continue
        direction = _fused(votes, validated)
        if direction:
            total += 1
            hits += (direction == 'CALL') == (actual > 0)
    oos = hits / total if total else None
    lower = wilson_lower_bound(hits, total)
    # Statistically strict: 95% Wilson lower bound must beat a coin flip (protects against lucky streaks).
    proven = bool(validated) and total >= MIN_OOS_SAMPLES and oos is not None and oos >= MIN_OOS_HIT_RATE and lower > 0.5
    return {'detectors': detectors, 'validated': sorted(validated), 'oosHitRate': None if oos is None else round(oos, 4),
            'oosSamples': total, 'oosLowerBound': round(lower, 4), 'trainPoints': len(train), 'proven': proven, 'candles': len(candles)}


def set_profile(key, profile):
    import time as _time
    PROFILES[key] = {**profile, 'at': _time.time()}


def profile_for(key):
    import time as _time
    profile = PROFILES.get(key)
    if profile and _time.time() - profile['at'] <= PROFILE_TTL_SECONDS * 3:
        return profile
    return None


_CACHE: Dict[Any, Dict[str, Any]] = {}


def cached_detect(candles):
    # One computation per closed candle and market keeps the event loop free for live ticks.
    if not candles:
        return detect(candles)
    last = candles[-1]
    key = (last.get('source'), last.get('symbol'), last.get('timeframe'), last.get('epoch'), len(candles), last.get('close'))
    if key not in _CACHE:
        if len(_CACHE) > 2000:
            _CACHE.clear()
        _CACHE[key] = detect(candles)
    return _CACHE[key]


def apply_layer(assessment: Dict[str, Any], candles: Sequence[Dict[str, Any]], market_key=None) -> Dict[str, Any]:
    """Fuse the algorithm layer into a signal assessment (fail-closed when STRICT)."""
    report = cached_detect(candles)
    profile = profile_for(market_key) if market_key else None
    assessment['algorithmLayer'] = {k: v for k, v in report.items() if k != 'detectors'} | {
        'detectors': [{k: d[k] for k in ('name', 'direction', 'probability', 'edge', 'detail')} for d in report.get('detectors', [])]}
    direction = assessment.get('direction')
    if direction not in {'CALL', 'PUT'} or not report['ready']:
        return assessment
    vetoes = list(assessment.get('vetoes') or [])
    if STRICT and report['vetoes']:
        vetoes.extend(report['vetoes'])
    if report['direction'] in {'CALL', 'PUT'} and report['direction'] != direction and report['edge'] >= MIN_EDGE:
        vetoes.append('ALGO_LAYER_OPPOSES_SIGNAL')
    assessment['algorithmLayer']['profile'] = profile and {k: profile.get(k) for k in ('validated', 'oosHitRate', 'oosSamples', 'oosLowerBound', 'proven')}
    if STRICT:
        # High-accuracy mode: only trade markets whose own history proves an out-of-sample edge,
        # and only when the proven detectors point the same way as the signal.
        if profile is None:
            vetoes.append('ALGO_PROFILE_PENDING')
        elif not profile['proven']:
            vetoes.append('ALGO_NO_PROVEN_EDGE')
        else:
            votes = {d['name']: (d['direction'], max(d['edge'], 1e-3)) for d in report['detectors']}
            fused = _fused(votes, set(profile['validated']))
            if fused != direction:
                vetoes.append('ALGO_PROVEN_DETECTORS_DISAGREE')
    if vetoes:
        assessment['vetoes'] = list(dict.fromkeys(vetoes))
        assessment['direction'] = 'NO_SIGNAL'
        assessment['confidence'] = 0
        assessment['reason'] = assessment['vetoes'][0]
        return assessment
    if profile and profile.get('oosHitRate'):
        # Honest confidence: never above the measured out-of-sample hit-rate of this market (+ small edge bonus).
        assessment['confidence'] = round(min(float(assessment.get('confidence', 0)), profile['oosHitRate'] * 100 + min(6.0, report['edge'] * 60.0)), 2)
    if report['direction'] == direction:
        agreeing = list(assessment.get('agreeing') or [])
        if 'algorithm_layer' not in agreeing:
            agreeing.append('algorithm_layer')
        assessment['agreeing'] = agreeing
        assessment['agreeCount'] = len(agreeing)
    return assessment
